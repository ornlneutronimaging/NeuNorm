"""Signature-guard tests for the released public entry points.

These pin the **positional** parameter order of every pipeline and of ``write_tiff_stack`` against
the last release, so a future parameter cannot be inserted mid-signature and silently re-bind every
argument after it.

That is not hypothetical. Commit 3bd2b07 (on ``next``, in no tag) inserted ``rebin_reduction``
immediately after ``rebin_by_tof`` in the three VENUS TOF pipelines and appended
``tiff_one_file_per_image``, shifting every later positional parameter — five of them in
``venus_tpx3_event``. ``write_tiff_stack`` likewise gained two positional parameters. Because none of
that had shipped, the fix was to make all four **keyword-only** rather than freeze the shift; these
guards now pin the v2.2.3 order and assert that everything added since is keyword-only.

**The expected lists below come from git tag v2.2.3, not from the code under test.** That matters: an
earlier version of this file was generated by introspecting the current signatures, so it pinned the
already-shifted order as "released" and could never have failed on the very regression it documents.
Regenerate these lists from the newest tag when a release happens, never from ``next``:

    git show v2.2.3:src/neunorm/pipelines/venus_tpx1.py

Appending a **keyword-only** parameter is always safe and needs no change here. Adding a positional
one, reordering, removing, or converting a released parameter to positional-only is a breaking change:
if a test fails, either revert it or treat it as a deliberate API break with a CHANGELOG entry.

Pattern follows ``test_rebin_tof_flexible.py::test_rebin_tof_preserves_legacy_positional_signature``,
which guards the leaf ``rebin_tof`` the same way.
"""

