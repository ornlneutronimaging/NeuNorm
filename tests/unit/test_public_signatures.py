@pytest.mark.parametrize("name", sorted(RELEASED_POSITIONAL))
def test_positional_signature_matches_the_last_release_exactly(name):
    """The positional parameters must equal the v2.2.3 list — same names, same order, nothing extra.

    A full-list comparison, not a prefix: pinning only a prefix would miss a positional parameter
    appended after it, which still shifts nothing today but silently becomes load-bearing order the
    moment another is added. Anything new belongs after a ``*`` marker, where it never appears here.
    """
    func, expected = RELEASED_POSITIONAL[name]
    params = inspect.signature(func).parameters
    # The two kinds that actually participate in positional re-binding. Filtering by "not KEYWORD_ONLY"
    # instead would count `*args` and `**kwargs` as positional, so adding either to an entry point would
    # fail this guard for a reason it does not mean.
    positional_kinds = (inspect.Parameter.POSITIONAL_ONLY, inspect.Parameter.POSITIONAL_OR_KEYWORD)
    actual = [n for n, p in params.items() if p.kind in positional_kinds]

    assert actual == expected, (
        f"{name}: positional signature no longer matches the v2.2.3 release.\n"
        f"  released: {expected}\n"
        f"  current:  {actual}\n"
        "Add new parameters as keyword-only (after a `*` marker) instead of positionally."
    )


@pytest.mark.parametrize("name", sorted(RELEASED_POSITIONAL))
def test_released_parameters_remain_callable_by_keyword(name):
    """Every released parameter must still be bindable by name.

    Checks the parameter *kind*, not just the name: converting ``f(a, b)`` to ``f(a, /, b)`` keeps
    both names and both positions, passes an order comparison, and yet breaks every ``f(a=...)``
    caller. Making a released parameter keyword-only would equally break positional callers, and is
    caught by the order test above.
    """
    func, expected = RELEASED_POSITIONAL[name]
    params = inspect.signature(func).parameters

    missing = [n for n in expected if n not in params]
    assert not missing, f"{name}: released parameter(s) removed: {missing}"

    wrong_kind = {
        n: params[n].kind.description for n in expected if params[n].kind is not params[n].POSITIONAL_OR_KEYWORD
    }
    assert not wrong_kind, (
        f"{name}: released parameter(s) are no longer positional-or-keyword: {wrong_kind}. "
        "Positional-only breaks keyword callers; keyword-only breaks positional callers."
    )


@pytest.mark.parametrize("name", sorted(RELEASED_POSITIONAL))
def test_everything_added_since_the_release_is_keyword_only(name):
    """Parameters added after v2.2.3 must be keyword-only, so they can never shift a released one.

    This is what makes the guard above stable over time: with every addition keyword-only, the
    positional list is frozen by construction and future growth cannot reorder it.

    ``*args`` and ``**kwargs`` are exempt, for the same reason the positional guard above names the two
    positional kinds explicitly: neither can displace a released parameter, so failing on them would be
    a false positive rather than a caught break.
    """
    func, expected = RELEASED_POSITIONAL[name]
    params = inspect.signature(func).parameters
    added = [n for n in params if n not in expected]
    shiftable_kinds = (inspect.Parameter.POSITIONAL_ONLY, inspect.Parameter.POSITIONAL_OR_KEYWORD)
    positionally_bindable = [n for n in added if params[n].kind in shiftable_kinds]

    assert not positionally_bindable, (
        f"{name}: parameter(s) added since v2.2.3 are positionally bindable: {positionally_bindable}. "
        "Put them after a `*` marker."
    )
